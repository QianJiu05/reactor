/* ============================================================
 *  查看端等待占位图
 *
 *  查看端先连、采集端后连时，服务器立刻回 200 + MJPEG 流头，
 *  先循环推一张「等待设备上线」的占位图；采集端一上线，
 *  下一帧真实数据自然就把占位图顶掉了 —— 查看端侧完全无感，
 *  也不需要为"等待中"单独维护一条 code path。
 *
 *  置 0 可关闭该功能：此时查看端先连会在建流后一直空白，
 *  直到采集端上线为止（TCP 连接保持，不报错）。
 * ============================================================ */
#define USING_WAITING_IMG   1
#define WAITING_IMG         "./waiting.jpg"    /* 占位图路径，缺失时自动降级 */
#define VIEWER_IDLE_FPS     1                  /* 等待期的占位图帧率 */

